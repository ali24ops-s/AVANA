export interface TeacherAcademicProfileInput {
  university?: string | null;
  faculty?: string | null;
  department?: string | null;
}

export interface TeacherAcademicProfile {
  university: string | null;
  faculty: string | null;
  department: string | null;
}

/**
 * Validates and normalizes teacher academic profile input.
 * Allows custom entries (open taxonomy) while enforcing sanitization and length bounds.
 */
export function validateTeacherAcademicProfile(
  input: unknown,
  options?: { isRequired?: boolean },
): {
  valid: boolean;
  error?: string;
  normalized?: TeacherAcademicProfile;
} {
  if (input == null || typeof input !== "object") {
    if (options?.isRequired) {
      return { valid: false, error: "اطلاعات آموزشی استاد الزامی است." };
    }
    return {
      valid: true,
      normalized: { university: null, faculty: null, department: null },
    };
  }

  const raw = input as Record<string, unknown>;

  const university =
    typeof raw.university === "string" ? raw.university.trim() : null;
  const faculty =
    typeof raw.faculty === "string" ? raw.faculty.trim() : null;
  const department =
    typeof raw.department === "string" ? raw.department.trim() : null;

  if (options?.isRequired) {
    if (!university || university.length < 2) {
      return {
        valid: false,
        error: "لطفاً دانشگاه محل تدریس خود را وارد یا انتخاب نمایید.",
      };
    }
    if (!department || department.length < 2) {
      return {
        valid: false,
        error: "لطفاً گروه آموزشی خود را وارد یا انتخاب نمایید.",
      };
    }
  }

  if (university && (university.length < 2 || university.length > 255)) {
    return {
      valid: false,
      error: "نام دانشگاه محل تدریس باید بین ۲ تا ۲۵۵ کاراکتر باشد.",
    };
  }

  if (faculty && (faculty.length < 2 || faculty.length > 255)) {
    return {
      valid: false,
      error: "نام دانشکده باید بین ۲ تا ۲۵۵ کاراکتر باشد.",
    };
  }

  if (department && (department.length < 2 || department.length > 255)) {
    return {
      valid: false,
      error: "نام گروه آموزشی باید بین ۲ تا ۲۵۵ کاراکتر باشد.",
    };
  }

  return {
    valid: true,
    normalized: {
      university: university || null,
      faculty: faculty || null,
      department: department || null,
    },
  };
}
