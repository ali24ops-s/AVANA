import { chromium, type Browser, type Page } from "playwright";
import {
  renderLessonPdfHtml,
  renderChapterPdfHtml,
  renderReviewSummaryPdfHtml,
  escapeHtml,
  type LessonPdfData,
  type ChapterPdfData,
  type ReviewSummaryPdfData,
} from "./pdf-template.js";

export interface PdfGenerationOptions {
  timeoutMs?: number;
}

export interface GeneratePdfRenderOptions {
  timeoutMs?: number;
  displayHeaderFooter?: boolean;
  headerTitle?: string;
  footerSubtitle?: string;
}

export class PdfGenerationService {
  private readonly defaultTimeoutMs: number;

  constructor(options?: PdfGenerationOptions) {
    this.defaultTimeoutMs = options?.timeoutMs ?? 20000;
  }

  /**
   * Generates a PDF buffer from an arbitrary pre-rendered HTML string.
   * Enforces strict network isolation (only data: and about: schemes are allowed)
   * and guarantees page and browser cleanup in all paths.
   */
  async generatePdfFromHtml(
    html: string,
    options?: GeneratePdfRenderOptions,
  ): Promise<Buffer> {
    if (!html || typeof html !== "string" || !html.trim()) {
      throw new Error("HTML content cannot be empty for PDF generation.");
    }

    let browser: Browser | null = null;
    let page: Page | null = null;
    const timeout = options?.timeoutMs ?? this.defaultTimeoutMs;

    try {
      browser = await chromium.launch({
        headless: true,
        args: [
          "--no-sandbox",
          "--disable-setuid-sandbox",
          "--disable-dev-shm-usage",
          "--disable-gpu",
        ],
      });

      page = await browser.newPage();
      page.setDefaultTimeout(timeout);

      // Block all external network / file requests for security (SSRF & LFI protection)
      // Only allow inlined data: URIs (e.g. base64 font/logo) and about: blank
      await page.route("**/*", (route) => {
        const url = route.request().url();
        if (url.startsWith("data:") || url.startsWith("about:")) {
          return route.continue();
        }
        return route.abort("blockedbyclient");
      });

      await page.setContent(html, {
        waitUntil: "networkidle",
        timeout,
      });

      // Ensure all embedded fonts (e.g. Estedad) are fully decoded and ready before rendering to PDF
      await page.evaluate(() => (globalThis as unknown as { document?: { fonts?: { ready?: Promise<unknown> } } }).document?.fonts?.ready);

      const displayHeaderFooter = options?.displayHeaderFooter ?? false;
      const headerTitle = options?.headerTitle ? escapeHtml(options.headerTitle) : "";
      const footerSubtitle = options?.footerSubtitle
        ? escapeHtml(options.footerSubtitle)
        : "آوانا • پلتفرم یادگیری دانشگاهی";

      const headerTemplate = `
        <div style="font-family: 'Estedad', 'Vazirmatn', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; font-size: 7.5pt; width: 100%; display: flex; justify-content: space-between; padding: 0 14mm; color: #94a3b8; direction: rtl; box-sizing: border-box;">
          <span>${headerTitle}</span>
          <span>آوانا • سامانه یادگیری دانشگاهی</span>
        </div>
      `;

      const footerTemplate = `
        <div style="font-family: 'Estedad', 'Vazirmatn', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; font-size: 7.5pt; width: 100%; display: flex; justify-content: space-between; padding: 0 14mm; color: #94a3b8; direction: rtl; box-sizing: border-box;">
          <span>${footerSubtitle}</span>
          <span>صفحه <span class="pageNumber"></span> از <span class="totalPages"></span></span>
        </div>
      `;

      const pdfUint8 = await page.pdf({
        format: "A4",
        printBackground: true,
        displayHeaderFooter,
        headerTemplate: displayHeaderFooter ? headerTemplate : undefined,
        footerTemplate: displayHeaderFooter ? footerTemplate : undefined,
        margin: {
          top: "16mm",
          bottom: "16mm",
          left: "14mm",
          right: "14mm",
        },
      });

      const pdfBuffer = Buffer.from(pdfUint8);

      // Basic validation: must start with %PDF-
      const header = pdfBuffer.subarray(0, 5).toString("utf-8");
      if (!header.startsWith("%PDF-")) {
        throw new Error("Invalid PDF header generated by renderer.");
      }

      return pdfBuffer;
    } finally {
      if (page) {
        await page.close().catch(() => {});
      }
      if (browser) {
        await browser.close().catch(() => {});
      }
    }
  }

  /**
   * Generates a PDF for an AVANA lesson using the canonical academic template.
   */
  async generateLessonPdf(data: LessonPdfData): Promise<Buffer> {
    if (!data.contentMarkdown || !data.contentMarkdown.trim()) {
      throw new Error("Lesson content is empty or incomplete.");
    }
    const html = renderLessonPdfHtml(data);
    return this.generatePdfFromHtml(html, {
      displayHeaderFooter: true,
      headerTitle: data.headerTitle || data.title,
      footerSubtitle: data.footerSubtitle || data.courseName || "آوانا",
    });
  }

  /**
   * Generates a single unified PDF for an entire chapter (all sessions in order)
   * using the canonical academic template with continuous page numbering.
   */
  async generateChapterPdf(data: ChapterPdfData): Promise<Buffer> {
    if (!data.sessions || !Array.isArray(data.sessions) || data.sessions.length === 0) {
      throw new Error("Chapter has no sessions for PDF generation.");
    }
    const hasContent = data.sessions.some(
      (s) => s.contentMarkdown && s.contentMarkdown.trim().length > 0,
    );
    if (!hasContent) {
      throw new Error("Chapter has no sessions with content for PDF generation.");
    }

    const html = renderChapterPdfHtml(data);
    return this.generatePdfFromHtml(html, {
      displayHeaderFooter: true,
      headerTitle: data.chapterTitle,
      footerSubtitle: data.courseName,
    });
  }

  /**
   * Generates a PDF for an AVANA review summary using the canonical review sheet template.
   */
  async generateReviewSummaryPdf(data: ReviewSummaryPdfData): Promise<Buffer> {
    const hasOverview = Boolean(data.overview && data.overview.trim());
    const hasSections = Array.isArray(data.sections) && data.sections.length > 0;
    const hasTakeaways = Array.isArray(data.finalTakeaways) && data.finalTakeaways.length > 0;

    if (!hasOverview && !hasSections && !hasTakeaways) {
      throw new Error("Review summary content is empty or incomplete.");
    }

    const html = renderReviewSummaryPdfHtml(data);
    return this.generatePdfFromHtml(html, {
      displayHeaderFooter: true,
      headerTitle: data.title,
      footerSubtitle: data.courseName || "خلاصه مرور آوانا",
    });
  }
}

export const defaultPdfGenerationService = new PdfGenerationService();

