import { chromium, type Browser, type Page } from "playwright";
import {
  renderLessonPdfHtml,
  renderReviewSummaryPdfHtml,
  type LessonPdfData,
  type ReviewSummaryPdfData,
} from "./pdf-template.js";

export interface PdfGenerationOptions {
  timeoutMs?: number;
}

export class PdfGenerationService {
  private readonly defaultTimeoutMs: number;

  constructor(options?: PdfGenerationOptions) {
    this.defaultTimeoutMs = options?.timeoutMs ?? 20000;
  }

  /**
   * Generates a PDF buffer from an arbitrary pre-rendered HTML string.
   * Enforces strict network isolation (only data: and about: schemes are allowed)
   * and guarantees page and browser cleanup in all paths.
   */
  async generatePdfFromHtml(html: string): Promise<Buffer> {
    if (!html || typeof html !== "string" || !html.trim()) {
      throw new Error("HTML content cannot be empty for PDF generation.");
    }

    let browser: Browser | null = null;
    let page: Page | null = null;

    try {
      browser = await chromium.launch({
        headless: true,
        args: [
          "--no-sandbox",
          "--disable-setuid-sandbox",
          "--disable-dev-shm-usage",
          "--disable-gpu",
        ],
      });

      page = await browser.newPage();
      page.setDefaultTimeout(this.defaultTimeoutMs);

      // Block all external network / file requests for security (SSRF & LFI protection)
      // Only allow inlined data: URIs (e.g. base64 font/logo) and about: blank
      await page.route("**/*", (route) => {
        const url = route.request().url();
        if (url.startsWith("data:") || url.startsWith("about:")) {
          return route.continue();
        }
        return route.abort("blockedbyclient");
      });

      await page.setContent(html, {
        waitUntil: "networkidle",
        timeout: this.defaultTimeoutMs,
      });

      const pdfUint8 = await page.pdf({
        format: "A4",
        printBackground: true,
        margin: {
          top: "16mm",
          bottom: "16mm",
          left: "14mm",
          right: "14mm",
        },
      });

      const pdfBuffer = Buffer.from(pdfUint8);

      // Basic validation: must start with %PDF-
      const header = pdfBuffer.subarray(0, 5).toString("utf-8");
      if (!header.startsWith("%PDF-")) {
        throw new Error("Invalid PDF header generated by renderer.");
      }

      return pdfBuffer;
    } finally {
      if (page) {
        await page.close().catch(() => {});
      }
      if (browser) {
        await browser.close().catch(() => {});
      }
    }
  }

  /**
   * Generates a PDF for an AVANA lesson using the canonical academic template.
   */
  async generateLessonPdf(data: LessonPdfData): Promise<Buffer> {
    if (!data.contentMarkdown || !data.contentMarkdown.trim()) {
      throw new Error("Lesson content is empty or incomplete.");
    }
    const html = renderLessonPdfHtml(data);
    return this.generatePdfFromHtml(html);
  }

  /**
   * Generates a PDF for an AVANA review summary using the canonical review sheet template.
   */
  async generateReviewSummaryPdf(data: ReviewSummaryPdfData): Promise<Buffer> {
    const hasOverview = Boolean(data.overview && data.overview.trim());
    const hasSections = Array.isArray(data.sections) && data.sections.length > 0;
    const hasTakeaways = Array.isArray(data.finalTakeaways) && data.finalTakeaways.length > 0;

    if (!hasOverview && !hasSections && !hasTakeaways) {
      throw new Error("Review summary content is empty or incomplete.");
    }

    const html = renderReviewSummaryPdfHtml(data);
    return this.generatePdfFromHtml(html);
  }
}

export const defaultPdfGenerationService = new PdfGenerationService();
